//! DEX parsing demo -- the Android compatibility track's capability proof,
//! same category of progress as `experimental::pe` was for Windows. See
//! `experimental::dex`'s module doc for the honest scope: this parses the DEX
//! *container format* and resolves its string/type/class tables, it does not
//! execute any bytecode.
//!
//! Unlike every ring-3 demo in this kernel, this one needs no address
//! space, no privilege transition, no trap handler -- DEX parsing is
//! pure data validation, so positive *and* negative testing both run
//! as ordinary function calls in the same boot, returning normally,
//! rather than needing a separate temporary-rebuild negative control
//! the way the ring-3/paging demos do. The negative checks below are
//! permanent, shipped code -- they run on every boot, not just once
//! during development.

use alloc::vec::Vec;

use crate::experimental::dex::{self, DexError};
use crate::serial_println;

/// A real, hand-constructed, checksum-and-signature-correct minimal
/// DEX file (`userprog/classes.dex`) -- zero classes/strings/methods,
/// but a genuine, spec-required `map_list` describing itself, built
/// and independently re-verified with Python's own `struct`/`hashlib`
/// before any Rust touched it (see the construction script referenced
/// in `IMPLEMENTATION_STATUS.md`).
static VALID_DEX: &[u8] = include_bytes!("../../userprog/classes.dex");

/// A second real DEX file (`userprog/classes_hello.dex`, built by
/// `tools/make_dex_fixture.py`), this one with contents: three strings, two
/// type descriptors, and one class definition. Its header, map list, checksum
/// and signature are the same format facts as the empty file's -- what it adds
/// is the tables the resolvers below read.
static CLASS_DEX: &[u8] = include_bytes!("../../userprog/classes_hello.dex");

/// The fixture's fixed layout, repeated here because the negative controls
/// corrupt specific fields and a control that patched the wrong byte would
/// pass for the wrong reason. `tools/make_dex_fixture.py` asserts every one of
/// these before it writes the file.
const STRING_IDS_OFF: usize = 0x70;
const FIRST_STRING_DATA_OFF: usize = 164;
/// The index of the last string’s terminating NUL -- i.e. where a file
/// that ends before its terminator stops. Used by the truncation control.
const LAST_STRING_TERMINATOR_OFF: usize = 217;
const FIRST_CLASS_DESCRIPTOR_OFF: usize = 165;

const EXPECTED_CLASS: &[u8] = b"Lnyrqis/hello/Hello;";
const EXPECTED_SUPER: &[u8] = b"Ljava/lang/Object;";
const EXPECTED_SOURCE: &[u8] = b"Hello.java";

/// The third real fixture (`userprog/classes_methods.dex`, also built by
/// `tools/make_dex_fixture.py`): the same class with one declared method,
/// `main([Ljava/lang/String;)V`, so the proto/method/class_data resolvers have
/// contents to answer for. Like the other two it is checksum- and
/// signature-correct and regenerated byte-identically.
static METHOD_DEX: &[u8] = include_bytes!("../../userprog/classes_methods.dex");

/// `classes_methods.dex`'s fixed layout, repeated for the same reason the class
/// fixture's is: the negative controls patch specific fields, and a control
/// that hit the wrong byte would pass for the wrong reason.
const METHOD_PROTO_IDS_OFF: usize = 0x9c;
const METHOD_CLASS_DEFS_OFF: usize = 0xb0;
const METHOD_TYPE_LIST_OFF: usize = 0x128;
const METHOD_CLASS_DATA_OFF: usize = 0x130;
const METHOD_SHORTY_STRING_INDEX: u32 = 4;
const METHOD_VOID_TYPE: u32 = 3;
const METHOD_PARAMETER_TYPE: u32 = 2;
const ACC_NATIVE: u32 = 0x100;
const EXPECTED_PARAM: &[u8] = b"[Ljava/lang/String;";

/// The fourth real fixture (`userprog/classes_fields.dex`, built by the same
/// script): a class with THREE fields and THREE methods, two of the methods
/// carrying real `code_item`s and one declared native. It exists for the three
/// format rules the earlier fixtures cannot show: `field_ids` resolve to names,
/// `class_data` indices are deltas accumulated per list, and `encoded_method` is
/// three ULEB128s -- the last being the method's `code_off`.
static FIELD_DEX: &[u8] = include_bytes!("../../userprog/classes_fields.dex");

/// `classes_fields.dex`'s fixed layout, repeated so each negative control
/// patches a byte this file names rather than an offset it guessed.
const FIELD_FIELD_IDS_OFF: usize = 0xcc;
const FIELD_CLASS_DEFS_OFF: usize = 0xfc;
const FIELD_SIZE_CODE_OFF: usize = 0x194;
const FIELD_RUN_CODE_OFF: usize = 0x1a8;
const FIELD_CLASS_DATA_OFF: usize = 0x1bc;
/// The fixture's class_data is this long; the controls below replace exactly
/// this span, so a replacement cannot silently move the map_list after it.
const FIELD_CLASS_DATA_LEN: usize = 22;
const FIELD_INT_TYPE: u32 = 2;
const FIELD_STRING_TYPE: u32 = 3;
const FIELD_COUNT_STRING: u32 = 3;
const FIELD_DEPTH_STRING: u32 = 4;
const FIELD_NAME_STRING: u32 = 5;
const ACC_ABSTRACT: u32 = 0x400;
const EXPECTED_FIELD_CLASS: &[u8] = b"Lnyrqis/hello/Fields;";
const EXPECTED_FIELD_INT: &[u8] = b"I";
const EXPECTED_FIELD_STRING: &[u8] = b"Ljava/lang/String;";

/// Runs the header proof, the table proof and every permanent negative check.
/// Returns `true` iff every part of the proof held.
pub fn run() -> bool {
    let kats_ok = run_known_answer_tests();
    let positive_ok = run_positive();
    let magic_check_ok = run_negative_bad_magic();
    let map_check_ok = run_negative_map_self_reference();
    let checksum_check_ok = run_negative_bad_checksum();
    let tables_ok = run_class_tables();
    let refusals_ok = run_negative_table_refusals();
    let methods_ok = run_method_tables();
    let method_refusals_ok = run_negative_method_refusals();
    let members_ok = run_field_and_code_tables();
    let member_refusals_ok = run_negative_member_refusals();

    serial_println!(
        "  experimental dex-demo self-test: crypto known-answer {}, valid parse+integrity {}, bad-magic rejection {}, map-self-reference rejection {}, checksum rejection {}, class tables {}, table refusals {}, method tables {}, method refusals {}, field and code tables {}, member refusals {} -- {}",
        verdict(kats_ok),
        verdict(positive_ok),
        verdict(magic_check_ok),
        verdict(map_check_ok),
        verdict(checksum_check_ok),
        verdict(tables_ok),
        verdict(refusals_ok),
        verdict(methods_ok),
        verdict(method_refusals_ok),
        verdict(members_ok),
        verdict(member_refusals_ok),
        verdict(kats_ok && positive_ok && magic_check_ok && map_check_ok && checksum_check_ok && tables_ok && refusals_ok && methods_ok && method_refusals_ok && members_ok && member_refusals_ok)
    );

    kats_ok
        && positive_ok
        && magic_check_ok
        && map_check_ok
        && checksum_check_ok
        && tables_ok
        && refusals_ok
        && methods_ok
        && method_refusals_ok
        && members_ok
        && member_refusals_ok
}

fn verdict(ok: bool) -> &'static str {
    if ok {
        "OK"
    } else {
        "FAILED"
    }
}

fn run_positive() -> bool {
    let info = match dex::parse(VALID_DEX) {
        Ok(info) => info,
        Err(e) => {
            serial_println!("  experimental dex-demo: FAILED to parse a valid DEX file: {:?}", e);
            return false;
        }
    };

    let ok = info.file_size == VALID_DEX.len() as u32
        && info.string_ids_count == 0
        && info.type_ids_count == 0
        && info.proto_ids_count == 0
        && info.field_ids_count == 0
        && info.method_ids_count == 0
        && info.class_defs_count == 0
        && info.map_entry_count == 1;

    serial_println!(
        "  experimental dex-demo: parsed a real DEX file (file_size={}, map_entry_count={}, all section counts zero as constructed) -- {}",
        info.file_size, info.map_entry_count, if ok { "OK" } else { "MISMATCH" }
    );

    // Integrity: the SAME real file's embedded Adler-32 checksum and
    // SHA-1 signature, recomputed in-kernel by experimental::crypto.
    match dex::verify(VALID_DEX) {
        Ok(()) => {
            serial_println!("  experimental dex-demo: Adler-32 checksum + SHA-1 signature verified in-kernel -- OK");
            ok
        }
        Err(e) => {
            serial_println!("  experimental dex-demo: DEX integrity verify FAILED: {:?}", e);
            false
        }
    }
}

/// The tables with contents: the string pool, the type descriptors that index
/// it, and the class definition that names both. Each fact is checked against
/// the fixture the generator wrote, and the class's descriptor is compared BY
/// BYTES -- a parser that resolved "a string" but the wrong one would fail here
/// rather than pass on a non-empty answer.
fn run_class_tables() -> bool {
    let info = match dex::parse(CLASS_DEX) {
        Ok(info) => info,
        Err(e) => {
            serial_println!("  experimental dex-demo: FAILED to parse classes_hello.dex: {:?}", e);
            return false;
        }
    };
    let integrity_ok = dex::verify(CLASS_DEX).is_ok();
    let counts_ok = info.file_size == CLASS_DEX.len() as u32
        && info.string_ids_count == 3
        && info.type_ids_count == 2
        && info.class_defs_count == 1;
    let strings_ok = matches!(dex::string(CLASS_DEX, 0), Ok(s) if s == EXPECTED_CLASS)
        && matches!(dex::string(CLASS_DEX, 1), Ok(s) if s == EXPECTED_SUPER)
        && matches!(dex::string(CLASS_DEX, 2), Ok(s) if s == EXPECTED_SOURCE);
    let types_ok = matches!(dex::type_descriptor(CLASS_DEX, 0), Ok(s) if s == EXPECTED_CLASS)
        && matches!(dex::type_descriptor(CLASS_DEX, 1), Ok(s) if s == EXPECTED_SUPER);
    let def = dex::class_def(CLASS_DEX, 0);
    let class_ok = match def {
        Ok(def) => {
            def.class_idx == 0
                && def.access_flags == 0x1
                && def.superclass_idx == Some(1)
                && def.source_file_idx == Some(2)
        }
        Err(_) => false,
    };
    // The descriptor is the answer a class loader would key on, so it is
    // checked through its own entry point rather than re-derived from the
    // indices above.
    let descriptor_ok = matches!(dex::class_descriptor(CLASS_DEX, 0), Ok(s) if s == EXPECTED_CLASS);

    let ok = integrity_ok && counts_ok && strings_ok && types_ok && class_ok && descriptor_ok;
    serial_println!(
        "  experimental dex-demo: class tables -- a {} byte DEX with {} string(s), {} type(s), {} class(es): string 0/1/2 answer \"{}\"/\"{}\"/\"{}\", type 0/1 resolve them as descriptors, and class 0 is {} (public, flags {:#x}) extending {} with source file {} -- {}",
        info.file_size,
        info.string_ids_count,
        info.type_ids_count,
        info.class_defs_count,
        "Lnyrqis/hello/Hello;",
        "Ljava/lang/Object;",
        "Hello.java",
        "Lnyrqis/hello/Hello;",
        0x1,
        "Ljava/lang/Object;",
        "Hello.java",
        if ok { "OK" } else { "MISMATCH" }
    );
    ok
}

/// Every malformed-table shape the resolvers must refuse, each exercised on a
/// copy of the real fixture with exactly one field broken, so the rejection
/// cannot be explained by any other check.
fn run_negative_table_refusals() -> bool {
    let string_offset = {
        let mut corrupted: Vec<u8> = CLASS_DEX.to_vec();
        corrupted[STRING_IDS_OFF..STRING_IDS_OFF + 4].copy_from_slice(&0xffffu32.to_le_bytes());
        matches!(dex::string(&corrupted, 0), Err(DexError::StringDataOutOfBounds))
    };

    let overlong_uleb = {
        let mut corrupted: Vec<u8> = CLASS_DEX.to_vec();
        // Five continuation bytes: a ULEB128 that never terminates inside the
        // format's five-byte bound.
        for i in 0..5 {
            corrupted[FIRST_STRING_DATA_OFF + i] = 0x80;
        }
        matches!(dex::string(&corrupted, 0), Err(DexError::BadUleb128))
    };

    let length_mismatch = {
        let mut corrupted: Vec<u8> = CLASS_DEX.to_vec();
        // The class descriptor is 20 bytes, i.e. 20 UTF-16 units; declare 19.
        corrupted[FIRST_STRING_DATA_OFF] = 19;
        matches!(dex::string(&corrupted, 0), Err(DexError::StringLengthMismatch))
    };

    let unterminated = {
        // The terminator of the LAST string is the last file byte before the
        // map_list, so overwriting it only makes the scan run into the map --
        // it still finds a NUL and fails on the length instead. The actual
        // "no terminator" case is a file that ENDS before one, so the fixture
        // is truncated at the last string's bytes. (`string` reads only the
        // header and the offsets it needs, so a short slice is exactly the
        // malformed file this check is about.)
        let truncated: Vec<u8> = CLASS_DEX[..LAST_STRING_TERMINATOR_OFF].to_vec();
        matches!(dex::string(&truncated, 2), Err(DexError::StringNotTerminated))
    };

    let type_past_end = matches!(
        dex::type_descriptor(CLASS_DEX, 2),
        Err(DexError::TypeIndexOutOfBounds)
    );
    let class_past_end = matches!(
        dex::class_def(CLASS_DEX, 1),
        Err(DexError::ClassIndexOutOfBounds)
    );
    let bad_descriptor = {
        let mut corrupted: Vec<u8> = CLASS_DEX.to_vec();
        corrupted[FIRST_CLASS_DESCRIPTOR_OFF] = b'X';
        matches!(
            dex::class_descriptor(&corrupted, 0),
            Err(DexError::BadTypeDescriptor)
        )
    };

    let ok = string_offset
        && overlong_uleb
        && length_mismatch
        && unterminated
        && type_past_end
        && class_past_end
        && bad_descriptor;
    serial_println!(
        "  experimental dex-demo: table refusals -- a string_data offset past EOF {}, an over-long ULEB128 {}, a declared UTF-16 length of 19 for 20 units {}, an unterminated string {}, a type index past the table {}, a class index past the table {}, and a class descriptor that does not start with L {} -- {}",
        if string_offset { "refused StringDataOutOfBounds" } else { "ACCEPTED" },
        if overlong_uleb { "refused BadUleb128" } else { "ACCEPTED" },
        if length_mismatch { "refused StringLengthMismatch" } else { "ACCEPTED" },
        if unterminated { "refused StringNotTerminated" } else { "ACCEPTED" },
        if type_past_end { "refused TypeIndexOutOfBounds" } else { "ACCEPTED" },
        if class_past_end { "refused ClassIndexOutOfBounds" } else { "ACCEPTED" },
        if bad_descriptor { "refused BadTypeDescriptor" } else { "ACCEPTED" },
        verdict(ok)
    );
    ok
}

/// Corrupts the magic's first byte in a heap-allocated copy and
/// confirms `dex::parse` rejects it with exactly `BadMagic` -- not
/// some other error, and not silently accepted.
fn run_negative_bad_magic() -> bool {
    let mut corrupted: Vec<u8> = VALID_DEX.to_vec();
    corrupted[0] = 0;
    let result = dex::parse(&corrupted);
    let rejected_correctly = matches!(result, Err(DexError::BadMagic));
    serial_println!(
        "  experimental dex-demo: corrupted magic -- parse result {:?}, correctly rejected: {}",
        result.err(), rejected_correctly
    );
    rejected_correctly
}

/// Corrupts the `map_list`'s single entry so it no longer describes
/// itself (changes its recorded file offset to a bogus value) and
/// confirms `dex::parse` rejects it with exactly `NoMapListEntry` --
/// proving the self-reference check is a real structural validation,
/// not just "is the count field nonzero."
fn run_negative_map_self_reference() -> bool {
    let mut corrupted: Vec<u8> = VALID_DEX.to_vec();
    let map_off = u32::from_le_bytes([corrupted[52], corrupted[53], corrupted[54], corrupted[55]]) as usize;
    let item_offset_field = map_off + 4 + 8; // map_item: type(2) + unused(2) + size(4) + offset(4)
    corrupted[item_offset_field..item_offset_field + 4].copy_from_slice(&999u32.to_le_bytes());
    let result = dex::parse(&corrupted);
    let rejected_correctly = matches!(result, Err(DexError::NoMapListEntry));
    serial_println!(
        "  experimental dex-demo: corrupted map self-reference -- parse result {:?}, correctly rejected: {}",
        result.err(), rejected_correctly
    );
    rejected_correctly
}

/// Known-answer tests for the Adler-32/SHA-1 primitives, independent of
/// the DEX file: a correct implementation must hit these published
/// vectors exactly, so a subtly wrong implementation can't pass just
/// because "the real bundled file happened to validate" (a wrong hash
/// that still matched the file's stored hash would be a coincidence of
/// two bugs cancelling -- these vectors rule that out directly).
fn run_known_answer_tests() -> bool {
    let adler = crate::experimental::crypto::adler32(b"Wikipedia");
    let adler_ok = adler == 0x11E6_0398;

    let digest = crate::experimental::crypto::sha1(b"abc");
    let expected: [u8; 20] = [
        0xa9, 0x99, 0x3e, 0x36, 0x47, 0x06, 0x81, 0x6a, 0xba, 0x3e, 0x25, 0x71, 0x78, 0x50, 0xc2, 0x6c, 0x9c,
        0xd0, 0xd8, 0x9d,
    ];
    let sha1_ok = digest == expected;

    serial_println!(
        "  experimental dex-demo: crypto known-answer -- Adler-32(\"Wikipedia\")={:#010x} (expected 0x11e60398) {}, SHA-1(\"abc\") 20-byte digest {}",
        adler,
        if adler_ok { "OK" } else { "MISMATCH" },
        if sha1_ok { "OK" } else { "MISMATCH" }
    );
    adler_ok && sha1_ok
}

/// Corrupts the header's stored Adler-32 checksum field (bytes 8..12,
/// which the checksum does NOT cover) and confirms `dex::verify`
/// rejects it with exactly `BadChecksum`. This is deliberately the one
/// integrity field that can be broken in isolation: changing it does
/// not alter the bytes the checksum is computed over, nor the SHA-1
/// signature, so nothing but the checksum check itself can be
/// responsible for the rejection.
fn run_negative_bad_checksum() -> bool {
    let mut corrupted: Vec<u8> = VALID_DEX.to_vec();
    corrupted[8] ^= 0xFF;
    let result = dex::verify(&corrupted);
    let rejected_correctly = matches!(result, Err(DexError::BadChecksum));
    let original_still_valid = dex::verify(VALID_DEX).is_ok();
    serial_println!(
        "  experimental dex-demo: corrupted checksum field -- verify result {:?}, correctly rejected: {}",
        result.err(), rejected_correctly
    );
    rejected_correctly && original_still_valid
}

/// The tables a method lives in: a proto_id (its signature), a method_id (its
/// class, proto and name), the type_list its parameters name, and the
/// class_data that lists it. The signature is COMPOSED from the resolved
/// pieces (name, parameter descriptors, return descriptor) and compared to the
/// bytes the fixture declares, so a parser that answered each field but put
/// them together wrongly would fail here.
fn run_method_tables() -> bool {
    let info = match dex::parse(METHOD_DEX) {
        Ok(info) => info,
        Err(e) => {
            serial_println!(
                "  experimental dex-demo: FAILED to parse classes_methods.dex: {:?}",
                e
            );
            return false;
        }
    };
    let integrity_ok = dex::verify(METHOD_DEX).is_ok();
    let counts_ok = info.file_size == METHOD_DEX.len() as u32
        && info.string_ids_count == 7
        && info.type_ids_count == 4
        && info.proto_ids_count == 1
        && info.method_ids_count == 1
        && info.class_defs_count == 1;

    let proto_ok = match dex::proto_id(METHOD_DEX, 0) {
        Ok(proto) => {
            proto.shorty_idx == METHOD_SHORTY_STRING_INDEX
                && proto.return_type_idx == METHOD_VOID_TYPE
                && matches!(dex::string(METHOD_DEX, proto.shorty_idx), Ok(shorty) if shorty == b"VL")
                && matches!(dex::type_descriptor(METHOD_DEX, proto.return_type_idx), Ok(t) if t == b"V")
                && matches!(dex::type_list(METHOD_DEX, proto.parameters_off), Ok(types) if types == [METHOD_PARAMETER_TYPE])
                && matches!(dex::type_descriptor(METHOD_DEX, METHOD_PARAMETER_TYPE), Ok(t) if t == EXPECTED_PARAM)
        }
        Err(_) => false,
    };

    let signature = compose_method_signature(METHOD_DEX, 0);
    let method_ok = match dex::method_id(METHOD_DEX, 0) {
        Ok(method) => {
            method.class_idx == 0
                && method.proto_idx == 0
                && matches!(dex::string(METHOD_DEX, method.name_idx), Ok(name) if name == b"main")
                && matches!(signature.as_deref(), Some(sig) if sig == b"main([Ljava/lang/String;)V")
        }
        Err(_) => false,
    };

    let (data_ok, group_counts, flags) = match dex::class_data(METHOD_DEX, 0) {
        Ok(Some(data)) => {
            let flags = data.direct_methods.first().map(|m| m.access_flags).unwrap_or(0);
            let index_ok = matches!(data.direct_methods.first(), Some(m) if m.index == 0);
            (
                data.static_fields.is_empty()
                    && data.instance_fields.is_empty()
                    && data.virtual_methods.is_empty()
                    && data.direct_methods.len() == 1
                    && index_ok
                    && flags == (0x1 | 0x8 | ACC_NATIVE),
                (
                    data.static_fields.len(),
                    data.instance_fields.len(),
                    data.direct_methods.len(),
                    data.virtual_methods.len(),
                ),
                flags,
            )
        }
        _ => (false, (0, 0, 0, 0), 0),
    };

    let ok = integrity_ok && counts_ok && proto_ok && method_ok && data_ok;
    serial_println!(
        "  experimental dex-demo: method tables -- a {} byte DEX with {} proto(s) and {} method(s): proto 0's shorty \"VL\" matches return type V and 1 parameter {}, method 0 is {} on {} with signature {} (flags {:#x}, ACC_PUBLIC|ACC_STATIC|ACC_NATIVE), listed in class_data with {} static / {} instance field(s) and {} direct / {} virtual method(s) -- {}",
        info.file_size,
        info.proto_ids_count,
        info.method_ids_count,
        "[Ljava/lang/String;",
        "main",
        "Lnyrqis/hello/Hello;",
        core::str::from_utf8(signature.as_deref().unwrap_or(&[])).unwrap_or("?"),
        flags,
        group_counts.0,
        group_counts.1,
        group_counts.2,
        group_counts.3,
        verdict(ok)
    );
    ok
}

/// Composes a method's signature from the resolved tables: name, then every
/// parameter descriptor in order, then the return descriptor. `None` when any
/// table refuses, so the caller compares one byte string rather than a set of
/// partly-resolved fields.
fn compose_method_signature(data: &[u8], index: u32) -> Option<Vec<u8>> {
    let method = dex::method_id(data, index).ok()?;
    let proto = dex::proto_id(data, method.proto_idx).ok()?;
    let mut signature = Vec::new();
    signature.extend_from_slice(dex::string(data, method.name_idx).ok()?);
    signature.push(b'(');
    for type_idx in dex::type_list(data, proto.parameters_off).ok()? {
        signature.extend_from_slice(dex::type_descriptor(data, type_idx).ok()?);
    }
    signature.push(b')');
    signature.extend_from_slice(dex::type_descriptor(data, proto.return_type_idx).ok()?);
    Some(signature)
}

/// Composes a field's qualified name the way the JVM/Dalvik name a field:
/// `<declaring class>.<name>:<type descriptor>`. Like the method composer this
/// is the answer a caller actually wants, so a reader that resolved each field
/// of a `field_id` but paired them wrongly fails on one byte compare.
fn compose_field_signature(data: &[u8], index: u32) -> Option<Vec<u8>> {
    let field = dex::field_id(data, index).ok()?;
    let mut signature = Vec::new();
    signature.extend_from_slice(dex::type_descriptor(data, field.class_idx).ok()?);
    signature.push(b'.');
    signature.extend_from_slice(dex::string(data, field.name_idx).ok()?);
    signature.push(b':');
    signature.extend_from_slice(dex::type_descriptor(data, field.type_idx).ok()?);
    Some(signature)
}

/// The tables a FIELD lives in, and the body a METHOD carries: `field_ids`
/// resolved to qualified names, `class_data`'s four member lists with their
/// deltas accumulated, and the two `code_item`s the fixture's methods point at.
///
/// The three checks that make this more than a non-empty answer:
///
/// - the instance field's delta is 2 and must resolve to index 2 -- a reader
///   that carried the static list's accumulator into the instance list would
///   compute 1 + 2 = 3 and be refused;
/// - the direct methods' deltas are 0, 1, 1 and must resolve to indices 0, 1, 2
///   -- a reader that treated a delta as an index would report 0, 1, 1;
/// - the two code_items' instruction words are compared to the exact encodings
///   the generator wrote (`const/4 v0, #0` then `return v0` / `return-void`), so
///   a reader that offset into the wrong bytes fails here.
fn run_field_and_code_tables() -> bool {
    let info = match dex::parse(FIELD_DEX) {
        Ok(info) => info,
        Err(e) => {
            serial_println!(
                "  experimental dex-demo: FAILED to parse classes_fields.dex: {:?}",
                e
            );
            return false;
        }
    };
    let integrity_ok = dex::verify(FIELD_DEX).is_ok();
    let counts_ok = info.file_size == FIELD_DEX.len() as u32
        && info.string_ids_count == 12
        && info.type_ids_count == 5
        && info.proto_ids_count == 2
        && info.field_ids_count == 3
        && info.method_ids_count == 3
        && info.class_defs_count == 1;

    let fields_ok = matches!(dex::field_id(FIELD_DEX, 0), Ok(f)
            if f.class_idx == 0
                && f.type_idx == FIELD_INT_TYPE
                && f.name_idx == FIELD_COUNT_STRING)
        && matches!(dex::string(FIELD_DEX, FIELD_COUNT_STRING), Ok(s) if s == b"COUNT")
        && matches!(dex::field_id(FIELD_DEX, 1), Ok(f)
            if f.name_idx == FIELD_DEPTH_STRING && f.type_idx == FIELD_INT_TYPE)
        && matches!(dex::field_id(FIELD_DEX, 2), Ok(f)
            if f.name_idx == FIELD_NAME_STRING && f.type_idx == FIELD_STRING_TYPE)
        && matches!(dex::type_descriptor(FIELD_DEX, FIELD_STRING_TYPE), Ok(t) if t == EXPECTED_FIELD_STRING)
        && matches!(compose_field_signature(FIELD_DEX, 2).as_deref(),
            Some(sig) if sig == b"Lnyrqis/hello/Fields;.name:Ljava/lang/String;");

    let (data_ok, indices_ok, code_ok) = match dex::class_data(FIELD_DEX, 0) {
        Ok(Some(data)) => {
            let indices = |members: &[dex::ClassMember]| -> Vec<u32> {
                members.iter().map(|m| m.index).collect()
            };
            let static_flags: Vec<u32> = data.static_fields.iter().map(|m| m.access_flags).collect();
            let direct: Vec<(u32, Option<u32>)> = data
                .direct_methods
                .iter()
                .map(|m| (m.index, m.code_off))
                .collect();
            (
                *indices(&data.static_fields) == [0, 1]
                    && static_flags == [0x19, 0x1a]
                    && *indices(&data.instance_fields) == [2]
                    && data.instance_fields[0].access_flags == 0x2
                    && data.virtual_methods.is_empty(),
                *indices(&data.direct_methods) == [0, 1, 2]
                    && direct[0].1 == Some(FIELD_SIZE_CODE_OFF as u32)
                    && direct[1].1.is_none()
                    && direct[2].1 == Some(FIELD_RUN_CODE_OFF as u32),
                direct.len() == 3
                    && data.direct_methods[1].access_flags == (0x1 | 0x8 | ACC_NATIVE),
            )
        }
        _ => (false, false, false),
    };

    let size_code = dex::code_item(FIELD_DEX, FIELD_SIZE_CODE_OFF as u32);
    let run_code = dex::code_item(FIELD_DEX, FIELD_RUN_CODE_OFF as u32);
    let size_ok = matches!(&size_code, Ok(code)
        if code.registers_size == 1
            && code.ins_size == 0
            && code.outs_size == 0
            && code.tries_size == 0
            && code.debug_info_off == 0
            && code.insns == [0x0012, 0x000f]);
    let run_ok = matches!(&run_code, Ok(code) if code.insns == [0x0012, 0x000e]);
    let signature_ok = matches!(compose_method_signature(FIELD_DEX, 2).as_deref(), Some(sig) if sig == b"run()V");

    let ok = integrity_ok
        && counts_ok
        && fields_ok
        && data_ok
        && indices_ok
        && code_ok
        && size_ok
        && run_ok
        && signature_ok;
    serial_println!(
        "  experimental dex-demo: field and code tables -- a {} byte DEX with {} field(s), {} method(s) and 2 code_item(s): field 2 composes to {}, class_data answers static field indices [0, 1], instance [2] (its own delta, not the static list's accumulator) and direct method indices [0, 1, 2], size()I carries a 2-word code_item at 0x194 reading [0x0012, 0x000f] (const/4 v0, #0; return v0) and run()V one at 0x1a8 writing and returning void, while make()V is ACC_NATIVE with code_off 0 -- {}",
        info.file_size,
        info.field_ids_count,
        info.method_ids_count,
        core::str::from_utf8(compose_field_signature(FIELD_DEX, 2).as_deref().unwrap_or(&[]))
            .unwrap_or("?"),
        verdict(ok)
    );
    ok
}

/// Appends a ULEB128, so the controls below can state a class_data the format's
/// own way instead of patching bytes whose lengths they would have to know.
fn push_uleb(out: &mut Vec<u8>, mut value: u32) {
    loop {
        let byte = (value & 0x7f) as u8;
        value >>= 7;
        if value == 0 {
            out.push(byte);
            return;
        }
        out.push(byte | 0x80);
    }
}

/// A `class_data` for `classes_fields.dex` with every delta and `code_off`
/// spelled out: counts (2 static, 1 instance, 3 direct, 0 virtual), then the
/// static field deltas, the instance field delta, and the three direct methods'
/// `(idx_diff, access_flags, code_off)`.
///
/// The canonical call is `fields_class_data([0, 1], 2, [(0, 0x9, 0x194),
/// (1, 0x109, 0), (1, 0x9, 0x1a8)])` -- the fixture's own bytes. Each control
/// changes exactly one of those numbers.
///
/// The result is exactly [`FIELD_CLASS_DATA_LEN`] bytes, or `None` when the
/// encoding would not fit. Both halves matter: a control exists to break one
/// claim in an otherwise real file, so a variant whose ULEB128s grew past the
/// span is refused here rather than overflowing it or being cut in half -- a
/// cut would leave a file whose map_list no longer sits where the header says,
/// and the map rule would then explain the refusal instead of the claim tested.
fn fields_class_data(
    static_deltas: [u32; 2],
    instance_delta: u32,
    methods: [(u32, u32, u32); 3],
) -> Option<Vec<u8>> {
    let mut out = Vec::new();
    for count in [2u32, 1, 3, 0] {
        push_uleb(&mut out, count);
    }
    push_uleb(&mut out, static_deltas[0]);
    push_uleb(&mut out, 0x19);
    push_uleb(&mut out, static_deltas[1]);
    push_uleb(&mut out, 0x1a);
    push_uleb(&mut out, instance_delta);
    push_uleb(&mut out, 0x2);
    for (delta, flags, code_off) in methods {
        push_uleb(&mut out, delta);
        push_uleb(&mut out, flags);
        push_uleb(&mut out, code_off);
    }
    if out.len() > FIELD_CLASS_DATA_LEN {
        return None;
    }
    // Trailing zeros are the span's unreachable tail: the four counts and the
    // deltas just written already stop the parse inside the item, so stating
    // the whole span here cannot hide a byte a control forgot to write.
    out.resize(FIELD_CLASS_DATA_LEN, 0);
    Some(out)
}

/// The fixture with its class_data replaced by `data`, or `None` unless `data`
/// is exactly the span the fixture reserves.
///
/// The fixture reserves [`FIELD_CLASS_DATA_LEN`] bytes for the item and the map
/// follows immediately, so the replacement is laid at its start rather than the
/// file being resized -- moving the map would make every control test a
/// different file.
///
/// Any other length is refused instead of fitted. Cutting a longer slice would
/// leave a file whose map_list no longer sits where the header says, so a
/// refusal about the map could explain the control and let it pass for the wrong
/// reason; padding a shorter one here would hide a control that never stated its
/// own trailing bytes. `fields_class_data` pads to the span, so every variant
/// arrives at exactly this length, and `None` reaches each caller as a clause
/// that printed NOT refused under a FAILED verdict -- never as a silent fit.
fn with_class_data(data: &[u8]) -> Option<Vec<u8>> {
    if data.len() != FIELD_CLASS_DATA_LEN {
        return None;
    }
    let mut corrupted = FIELD_DEX.to_vec();
    corrupted[FIELD_CLASS_DATA_OFF..FIELD_CLASS_DATA_OFF + FIELD_CLASS_DATA_LEN]
        .copy_from_slice(data);
    Some(corrupted)
}

/// The fixture with a control's class_data spliced in, or `None` when the
/// control's variant could not be built at all: an encoding that grew past the
/// span, or a slice of the wrong length.
fn fields_variant(
    static_deltas: [u32; 2],
    instance_delta: u32,
    methods: [(u32, u32, u32); 3],
) -> Option<Vec<u8>> {
    with_class_data(&fields_class_data(static_deltas, instance_delta, methods)?)
}

/// Every malformed member/code shape the new tables must refuse, each on a copy
/// of the real fixture with one claim broken: a field index past its table, a
/// static delta that lands past it, a native method carrying a non-zero code_off,
/// an ordinary method without any, a code_off past EOF, a method delta that lands past
/// method_ids, a code_item whose words run past EOF, one whose argument window
/// exceeds its frame, one whose entry stops before its code_off, and the span
/// rule those copies rest on: a class_data that is not exactly the length the
/// fixture reserves is refused, never fitted or cut.
fn run_negative_member_refusals() -> bool {
    // A clause that did not refuse prints NOT refused, never ACCEPTED: with the
    // span rule above, "the control's file was never built" and "the parser
    // accepted it" are both `false`, so the word must not claim the second.
    const NOT_REFUSED: &str = "NOT refused";

    let field_past = matches!(
        dex::field_id(FIELD_DEX, 3),
        Err(DexError::FieldIndexOutOfBounds)
    );

    let delta_past = match fields_variant(
        [0, 4],
        2,
        [(0, 0x9, FIELD_SIZE_CODE_OFF as u32), (1, 0x109, 0), (1, 0x9, FIELD_RUN_CODE_OFF as u32)],
    ) {
        Some(corrupted) => {
            matches!(dex::class_data(&corrupted, 0), Err(DexError::FieldIndexOutOfBounds))
        }
        None => false,
    };

    // ACC_NATIVE is 0x100, so the flags alone take two ULEB128 bytes; a native
    // method carrying a real body offset (0x194, also two bytes) would make this
    // entry five bytes and the item 23 -- one past the span. The control carries
    // a ONE-byte non-zero code_off instead: same rule, same item width, and only
    // one claim broken. It also pins the order of the rule: offset 1 is inside
    // the file but not a code_item, so a version that resolved the offset before
    // reading the flags would answer CodeItemTruncated, not MethodCodeMismatch.
    let native_with_code = match fields_variant(
        [0, 1],
        2,
        [
            (0, 0x9, FIELD_SIZE_CODE_OFF as u32),
            (1, 0x1 | 0x8 | ACC_NATIVE, 1),
            (1, 0x9, FIELD_RUN_CODE_OFF as u32),
        ],
    ) {
        Some(corrupted) => {
            matches!(dex::class_data(&corrupted, 0), Err(DexError::MethodCodeMismatch))
        }
        None => false,
    };

    let ordinary_without_code = match fields_variant(
        [0, 1],
        2,
        [(0, 0x9, 0), (1, 0x109, 0), (1, 0x9, FIELD_RUN_CODE_OFF as u32)],
    ) {
        Some(corrupted) => {
            matches!(dex::class_data(&corrupted, 0), Err(DexError::MethodCodeMismatch))
        }
        None => false,
    };

    // ACC_ABSTRACT is the rule's other flag, and a body-less abstract method is
    // the legal case: accepted, so the check is not just "is this native".
    let abstract_without_code_ok = match fields_variant(
        [0, 1],
        2,
        [
            (0, 0x9, FIELD_SIZE_CODE_OFF as u32),
            (1, 0x1 | ACC_ABSTRACT, 0),
            (1, 0x9, FIELD_RUN_CODE_OFF as u32),
        ],
    ) {
        Some(corrupted) => matches!(dex::class_data(&corrupted, 0), Ok(Some(_))),
        None => false,
    };
    // ACC_ABSTRACT is the rule's other flag: same width budget as above, so this
    // one also carries a one-byte non-zero code_off.
    let abstract_with_code = match fields_variant(
        [0, 1],
        2,
        [
            (0, 0x9, FIELD_SIZE_CODE_OFF as u32),
            (1, 0x1 | 0x8 | ACC_ABSTRACT, 1),
            (1, 0x9, FIELD_RUN_CODE_OFF as u32),
        ],
    ) {
        Some(corrupted) => {
            matches!(dex::class_data(&corrupted, 0), Err(DexError::MethodCodeMismatch))
        }
        None => false,
    };

    // 4080 is past the 604-byte file by any margin, and its ULEB128 is two
    // bytes like the offsets it replaces -- so this control breaks the OFFSET
    // and nothing about the item's shape.
    let code_past_eof = match fields_variant(
        [0, 1],
        2,
        [(0, 0x9, 4080), (1, 0x109, 0), (1, 0x9, FIELD_RUN_CODE_OFF as u32)],
    ) {
        Some(corrupted) => {
            matches!(dex::class_data(&corrupted, 0), Err(DexError::CodeItemOutOfBounds))
        }
        None => false,
    };

    let method_delta_past = match fields_variant(
        [0, 1],
        2,
        [
            (0, 0x9, FIELD_SIZE_CODE_OFF as u32),
            (5, 0x109, 0),
            (1, 0x9, FIELD_RUN_CODE_OFF as u32),
        ],
    ) {
        Some(corrupted) => {
            matches!(dex::class_data(&corrupted, 0), Err(DexError::MethodIndexOutOfBounds))
        }
        None => false,
    };

    let insns_past_eof = {
        let mut corrupted: Vec<u8> = FIELD_DEX.to_vec();
        corrupted[FIELD_SIZE_CODE_OFF + 12..FIELD_SIZE_CODE_OFF + 16]
            .copy_from_slice(&0xffffu32.to_le_bytes());
        matches!(
            dex::code_item(&corrupted, FIELD_SIZE_CODE_OFF as u32),
            Err(DexError::CodeItemTruncated)
        )
    };

    let args_beyond_frame = {
        let mut corrupted: Vec<u8> = FIELD_DEX.to_vec();
        corrupted[FIELD_SIZE_CODE_OFF + 2..FIELD_SIZE_CODE_OFF + 4]
            .copy_from_slice(&2u16.to_le_bytes());
        matches!(
            dex::code_item(&corrupted, FIELD_SIZE_CODE_OFF as u32),
            Err(DexError::CodeItemRegisterMismatch)
        )
    };

    let entry_truncated = {
        // The counts and both static fields are intact; the file stops after the
        // first method's index and flags, before its code_off.
        let cut = &FIELD_DEX[..FIELD_CLASS_DATA_OFF + 10];
        matches!(dex::class_data(cut, 0), Err(DexError::ClassDataTruncated))
    };

    // The span rule the copies above rest on, as a control of its own: the
    // canonical encoding pads to exactly the reserved span, a variant whose
    // code_off grew to a five-byte ULEB128 is refused by the builder instead of
    // overflowing it, and a replacement one byte either side of the span is
    // refused instead of being cut or padded into a plausible file.
    let canonical_fits = matches!(
        fields_class_data(
            [0, 1],
            2,
            [(0, 0x9, FIELD_SIZE_CODE_OFF as u32), (1, 0x109, 0), (1, 0x9, FIELD_RUN_CODE_OFF as u32)],
        ),
        Some(bytes) if bytes.len() == FIELD_CLASS_DATA_LEN
    );
    let grown_past_span = fields_class_data(
        [0, 1],
        2,
        [(0, 0x9, u32::MAX), (1, 0x109, 0), (1, 0x9, FIELD_RUN_CODE_OFF as u32)],
    )
    .is_none();
    let span_guard = canonical_fits
        && grown_past_span
        && with_class_data(&[0u8; FIELD_CLASS_DATA_LEN - 1]).is_none()
        && with_class_data(&[0u8; FIELD_CLASS_DATA_LEN + 1]).is_none();

    let code_at_zero = matches!(
        dex::code_item(FIELD_DEX, 0),
        Err(DexError::CodeItemOutOfBounds)
    );

    let ok = field_past
        && delta_past
        && native_with_code
        && ordinary_without_code
        && abstract_without_code_ok
        && abstract_with_code
        && code_past_eof
        && method_delta_past
        && insns_past_eof
        && args_beyond_frame
        && entry_truncated
        && span_guard
        && code_at_zero;
    serial_println!(
        "  experimental dex-demo: member refusals -- a field index past field_ids {}, a static delta landing past it {}, a native method carrying a non-zero code_off {}, an ordinary method with none {}, an ABSTRACT method carrying one {} (while a native method without one is accepted {}), a code_off past EOF {}, a method delta landing past method_ids {}, a code_item whose words run past EOF {}, one whose ins_size exceeds its registers {}, an entry that stops before its code_off {}, a class_data replacement one byte short, one byte long or an encoding grown past the span {}, and code_item(0) {} -- {}",
        if field_past { "refused FieldIndexOutOfBounds" } else { NOT_REFUSED },
        if delta_past { "refused FieldIndexOutOfBounds" } else { NOT_REFUSED },
        if native_with_code { "refused MethodCodeMismatch before the offset was resolved" } else { NOT_REFUSED },
        if ordinary_without_code { "refused MethodCodeMismatch" } else { NOT_REFUSED },
        if abstract_with_code { "refused MethodCodeMismatch" } else { NOT_REFUSED },
        if abstract_without_code_ok { "OK" } else { "refused" },
        if code_past_eof { "refused CodeItemOutOfBounds" } else { NOT_REFUSED },
        if method_delta_past { "refused MethodIndexOutOfBounds" } else { NOT_REFUSED },
        if insns_past_eof { "refused CodeItemTruncated" } else { NOT_REFUSED },
        if args_beyond_frame { "refused CodeItemRegisterMismatch" } else { NOT_REFUSED },
        if entry_truncated { "refused ClassDataTruncated" } else { NOT_REFUSED },
        if span_guard { "refused by the span rule" } else { "FITTED" },
        if code_at_zero { "refused CodeItemOutOfBounds" } else { NOT_REFUSED },
        verdict(ok)
    );
    ok
}

/// Every malformed method-table shape the resolvers must refuse, each on a copy
/// of the real fixture with one field broken: a proto or method index past its
/// table, a class_data offset past EOF, a class_data whose counts overrun the
/// bytes, a parameter list offset past EOF, a parameter type past the type
/// table, a shorty that disagrees with the parameter count, and a class_data
/// naming a field or method the tables cannot answer.
fn run_negative_method_refusals() -> bool {
    let proto_past = matches!(
        dex::proto_id(METHOD_DEX, 1),
        Err(DexError::ProtoIndexOutOfBounds)
    );
    let method_past = matches!(
        dex::method_id(METHOD_DEX, 1),
        Err(DexError::MethodIndexOutOfBounds)
    );

    let class_data_past = {
        let mut corrupted: Vec<u8> = METHOD_DEX.to_vec();
        corrupted[METHOD_CLASS_DEFS_OFF + 24..METHOD_CLASS_DEFS_OFF + 28]
            .copy_from_slice(&0xffffu32.to_le_bytes());
        matches!(
            dex::class_data(&corrupted, 0),
            Err(DexError::ClassDataOutOfBounds)
        )
    };

    let truncated = {
        // The counts are intact, but the file stops right after them: the one
        // declared direct method has no index/flags bytes left to read.
        let cut = &METHOD_DEX[..METHOD_CLASS_DATA_OFF + 4];
        matches!(dex::class_data(cut, 0), Err(DexError::ClassDataTruncated))
    };

    let params_past = {
        let mut corrupted: Vec<u8> = METHOD_DEX.to_vec();
        corrupted[METHOD_PROTO_IDS_OFF + 8..METHOD_PROTO_IDS_OFF + 12]
            .copy_from_slice(&0xffffu32.to_le_bytes());
        matches!(dex::proto_id(&corrupted, 0), Err(DexError::TypeListOutOfBounds))
    };

    let param_type_past = {
        let mut corrupted: Vec<u8> = METHOD_DEX.to_vec();
        corrupted[METHOD_TYPE_LIST_OFF + 4..METHOD_TYPE_LIST_OFF + 6]
            .copy_from_slice(&9u16.to_le_bytes());
        matches!(
            dex::proto_id(&corrupted, 0),
            Err(DexError::TypeIndexOutOfBounds)
        )
    };

    let shorty_mismatch = {
        // String 5 is "V" -- a legal shorty character, but one unit for a proto
        // that declares a return value AND a parameter (two units expected).
        let mut corrupted: Vec<u8> = METHOD_DEX.to_vec();
        corrupted[METHOD_PROTO_IDS_OFF..METHOD_PROTO_IDS_OFF + 4]
            .copy_from_slice(&5u32.to_le_bytes());
        matches!(
            dex::proto_id(&corrupted, 0),
            Err(DexError::ShortyLengthMismatch)
        )
    };

    let field_past = {
        let mut corrupted: Vec<u8> = METHOD_DEX.to_vec();
        corrupted[METHOD_CLASS_DATA_OFF..METHOD_CLASS_DATA_OFF + 7]
            .copy_from_slice(&[1, 0, 0, 0, 99, 0, 0]);
        matches!(
            dex::class_data(&corrupted, 0),
            Err(DexError::FieldIndexOutOfBounds)
        )
    };

    let method_index_past = {
        let mut corrupted: Vec<u8> = METHOD_DEX.to_vec();
        corrupted[METHOD_CLASS_DATA_OFF..METHOD_CLASS_DATA_OFF + 7]
            .copy_from_slice(&[0, 0, 1, 0, 5, 0, 0]);
        matches!(
            dex::class_data(&corrupted, 0),
            Err(DexError::MethodIndexOutOfBounds)
        )
    };

    let ok = proto_past
        && method_past
        && class_data_past
        && truncated
        && params_past
        && param_type_past
        && shorty_mismatch
        && field_past
        && method_index_past;
    serial_println!(
        "  experimental dex-demo: method refusals -- a proto index past the table {}, a method index past the table {}, a class_data offset past EOF {}, a class_data whose counts overrun the file {}, a parameter list offset past EOF {}, a parameter type past the type table {}, a shorty disagreeing with its parameter count {}, a class_data field index past field_ids {}, and a class_data method index past method_ids {} -- {}",
        if proto_past { "refused ProtoIndexOutOfBounds" } else { "ACCEPTED" },
        if method_past { "refused MethodIndexOutOfBounds" } else { "ACCEPTED" },
        if class_data_past { "refused ClassDataOutOfBounds" } else { "ACCEPTED" },
        if truncated { "refused ClassDataTruncated" } else { "ACCEPTED" },
        if params_past { "refused TypeListOutOfBounds" } else { "ACCEPTED" },
        if param_type_past { "refused TypeIndexOutOfBounds" } else { "ACCEPTED" },
        if shorty_mismatch { "refused ShortyLengthMismatch" } else { "ACCEPTED" },
        if field_past { "refused FieldIndexOutOfBounds" } else { "ACCEPTED" },
        if method_index_past { "refused MethodIndexOutOfBounds" } else { "ACCEPTED" },
        verdict(ok)
    );
    ok
}
