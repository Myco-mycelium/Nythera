#!/usr/bin/env python3
"""Build-time assets of the AndroWin-style desktop shell `desk` (increment 1-54): Roboto glyph masks (OFL-1.1) and Material icon masks (Apache-2.0, third_party/material-icons)
-> userprog/desk/src/{font.bin,icons.bin,assets.rs}. Rust reads them with include_bytes!; the independent checker (tools/check_desk.py) re-rasterizes from the same sources by its own code path."""
import os, sys, struct
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, HERE)
import fontgen, svgraster
OUT = os.path.join(HERE, '..', 'userprog', 'desk', 'src'); ICON_DIR = os.path.join(HERE, '..', 'third_party', 'material-icons', 'filled')
FACES = [('R12', 400, 12), ('R13', 400, 13), ('R14', 400, 14), ('M11', 500, 11), ('M12', 500, 12), ('M13', 500, 13), ('M14', 500, 14), ('M16', 500, 16), ('M22', 500, 22)]
ICONS = [('grid_view', 24), ('sports_esports', 24), ('language', 24), ('folder', 24), ('terminal', 24), ('view_quilt', 18), ('remove', 18), ('close', 18),
         ('notifications', 18), ('keyboard_arrow_down', 18), ('wifi', 16), ('bluetooth', 16), ('sports_esports', 16), ('battery_charging_full', 16), ('search', 20),
         ('settings', 20), ('power_settings_new', 20), ('chevron_right', 14), ('sports_esports', 28), ('language', 28), ('folder', 28), ('terminal', 28), ('sports_esports', 22), ('settings', 24), ('person', 24), ('search', 18),
         ('wifi', 20), ('bluetooth', 20), ('sports_esports', 20), ('do_not_disturb_on', 20), ('nightlight', 20), ('airplanemode_active', 20), ('close', 14), ('brightness_6', 20), ('volume_up', 20),
         ('keyboard_arrow_up', 18), ('description', 24), ('arrow_back', 18), ('settings', 28)]
def main():
    masks, table, heads = fontgen.build([(w, px) for _, w, px in FACES])
    words = []
    for f in range(len(FACES)): words += [heads[f][0], heads[f][1]]
    for f in range(len(FACES)):
        for g in table[f]: words += list(g)
    open(os.path.join(OUT, 'font.bin'), 'wb').write(struct.pack('<%di' % len(words), *words) + masks)
    tab = bytearray(); offs = []
    for name, sz in ICONS:
        offs.append(len(tab)); tab += svgraster.raster(svgraster.load(os.path.join(ICON_DIR, name + '.svg')), sz)
    open(os.path.join(OUT, 'icons.bin'), 'wb').write(bytes(tab))
    rs = ["// generated by tools/make_desk_assets.py -- do not edit", "pub static FONT: &[u8] = include_bytes!(\"font.bin\");", "pub static ICONS: &[u8] = include_bytes!(\"icons.bin\");",
          "pub const NFACES: usize = %d;" % len(FACES), "pub const MASK_BASE: usize = %d;" % (len(words) * 4)]
    for i, (n, w, px) in enumerate(FACES): rs.append("pub const %s: usize = %d;" % (n, i))
    rs.append("pub const ICON_TAB: [(usize, usize); %d] = [%s];" % (len(ICONS), ", ".join("(%d, %d)" % (o, sz) for o, (n, sz) in zip(offs, ICONS))))
    for i, (n, sz) in enumerate(ICONS): rs.append("pub const I_%s_%d: usize = %d;" % (n.upper(), sz, i))
    open(os.path.join(OUT, 'assets.rs'), 'w').write("\n".join(rs) + "\n")
    print('font %d bytes, icons %d bytes' % (len(words) * 4 + len(masks), len(tab)))
if __name__ == '__main__': main()
