#!/usr/bin/env python3
"""Generate userprog/font5x7.inc (7 bytes per glyph, bit 4 = leftmost cell; order A..Z then space) from tools/font5x7.txt."""
import sys
def parse(path='tools/font5x7.txt'):
    g, cur = {}, None
    ext = path != 'tools/font5x7.txt' and False
    for ln in open(path).read().splitlines():
        if ln.startswith(';') or not ln.strip(): continue
        if ln.startswith('glyph '): cur = ' ' if ln[6:] == 'SPACE' else (':' if ln[6:] == 'COLON' else ln[6:]); g[cur] = []
        else:
            assert len(ln) == 5 and set(ln) <= set('#.'), ln
            g[cur].append(sum((1 << (4 - i)) for i, c in enumerate(ln) if c == '#'))
    for k, v in g.items(): assert len(v) == 7, k
    return g
ORDER = [chr(65 + i) for i in range(26)] + [' ']
EXT = [str(i) for i in range(10)] + [':']
def shell_rs(g, e):
    out = '// GENERATED by tools/make_font.py from tools/font5x7.txt + tools/font_ext.txt -- do not edit.\n// 38 glyphs x 7 rows, bit 4 = leftmost cell. Index: A-Z = 0..25, space = 26, 0-9 = 27..36, colon = 37.\npub const GLYPHS: [[u8; 7]; 38] = [\n'
    for k in ORDER + EXT:
        src = g if k in g else e
        out += '    [' + ', '.join('0x%02x' % b for b in src[k]) + '],  // ' + ('SPACE' if k == ' ' else k) + '\n'
    return out + '];\n'
if __name__ == '__main__':
    g = parse(); assert list(g) == ORDER
    e = parse('tools/font_ext.txt'); assert list(e) == EXT, list(e)
    open('shell/src/font_data.rs', 'w').write(shell_rs(g, e))
    out = '/* GENERATED by tools/make_font.py from tools/font5x7.txt -- do not edit. 27 glyphs x 7 rows (A..Z, space). */\nfont:\n'
    for k in ORDER: out += '    .byte ' + ','.join('0x%02x' % b for b in g[k]) + '    /* ' + ('SPACE' if k == ' ' else k) + ' */\n'
    # PS/2 scancode set 1 (make codes) -> glyph index 0..25, 0xff = not a letter. Rows: QWERTYUIOP = 0x10..0x19, ASDFGHJKL = 0x1e..0x26, ZXCVBNM = 0x2c..0x32.
    km = [0xff] * 0x33
    for base, row in ((0x10, 'QWERTYUIOP'), (0x1e, 'ASDFGHJKL'), (0x2c, 'ZXCVBNM')):
        for k, ch in enumerate(row): km[base + k] = ord(ch) - 65
    out += 'keymap:\n' + ''.join('    .byte ' + ','.join('0x%02x' % b for b in km[r:r + 16]) + '\n' for r in range(0, 0x33, 16))
    open(sys.argv[1] if len(sys.argv) > 1 else 'userprog/font5x7.inc', 'w').write(out)
