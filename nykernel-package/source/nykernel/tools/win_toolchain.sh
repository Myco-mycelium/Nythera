#!/usr/bin/env bash
#
# win_toolchain.sh -- put a GCC/binutils/GRUB/QEMU toolchain on PATH when the
# tree is built from Windows (Git Bash / MSYS2) instead of Linux.
#
# Why this exists: build.sh, make_live_iso.sh and check_live_iso.sh were
# written against a Linux host, where `as`, `ld`, `strip`, `grub-mkrescue`,
# `xorriso`, `mtools` and `qemu-system-x86_64` come from distro packages. On
# Windows none of them exist, and the tools that DO exist are split across two
# GNU ld emulations that cannot be mixed:
#
#   * the kernel and the userprog test objects are ELF64, linked with the
#     multiboot2 linker scripts (x86_64-elf-ld);
#   * the Win32 surface (kernel32.dll, nyrqis.dll, win32_console.exe, the PE
#     bound-import carriers) is PE32+, linked by the MinGW ld with
#     `-m i386pep`.
#
# No single Windows `ld` supports both (the MinGW one reports only
# i386pep/i386pe), so this script installs tiny dispatchers named
# `as`/`ld`/`objdump`/`strip`/`readelf` in a private bin directory and
# prepends that directory, the ELF toolchain, MinGW's binutils, MSYS2's
# xorriso/mtools/QEMU and the GRUB utilities to PATH. The dispatch rule is
# deliberately mechanical, so it cannot silently pick the wrong emulation:
#
#   as       PE sources (userprog/prog_pe*.s, userprog/prog_win32_*.s) go to
#            MinGW as; every other .s is ELF and goes to x86_64-elf-as.
#   ld       a command line containing `-m i386pep` is a PE link and goes to
#            MinGW ld; anything else is ELF and goes to x86_64-elf-ld. A PE
#            link's image timestamps are then written to SOURCE_DATE_EPOCH,
#            because MinGW's ld ignores that variable (see pe_stamp below).
#   objdump  .dll/.exe operands are PE and go to MinGW objdump; otherwise the
#            ELF objdump.
#   strip / readelf
#            always the ELF tools: the only users are the kernel image and
#            the ELF userprog artifacts.
#
# Layout it expects under $NYKERNEL_WIN_TOOLS (default
# ~/.cache/nyrqis-win-tools), each fetched/prepared once, by hand:
#
#   elf/bin/x86_64-elf-{as,ld,objdump,strip,readelf}.exe
#                                  x86_64-elf-tools-windows.zip (GCC 15.2.0)
#   msys64/                        msys2-x86_64-latest.tar.xz, with pacman
#                                  packages mingw-w64-ucrt-x86_64-binutils,
#                                  mingw-w64-ucrt-x86_64-gcc,
#                                  mingw-w64-ucrt-x86_64-qemu,
#                                  mingw-w64-ucrt-x86_64-mtools and xorriso
#   grub/grub-2.06-for-windows/    grub-2.06-for-windows.zip (grub-mkimage +
#                                  the i386-pc module tree; there is no
#                                  grub-mkrescue for Windows)
#   ovmf/x64/{code,vars}.fd        the firmware blobs check_live_iso.sh boots
#
# Nothing here touches the host: the toolchain is a directory tree, and the
# dispatchers are files inside it.
#
# Usage: sourced, never executed directly:
#
#   [[ "$(uname -s)" == MINGW* || "$(uname -s)" == MSYS* ]] && \
#       source "$(dirname "$0")/tools/win_toolchain.sh"

WIN_TOOLS="${NYKERNEL_WIN_TOOLS:-$HOME/.cache/nyrqis-win-tools}"

_win_tools_fail() {
    echo "FAIL: $*" >&2
    echo "      (the Windows toolchain under $WIN_TOOLS is incomplete;" >&2
    echo "       see tools/win_toolchain.sh for the layout it expects)" >&2
    return 1
}

for d in elf/bin msys64/ucrt64/bin msys64/usr/bin grub/grub-2.06-for-windows; do
    [[ -d "$WIN_TOOLS/$d" ]] || { _win_tools_fail "missing $WIN_TOOLS/$d"; return 1; }
done
for f in elf/bin/x86_64-elf-ld.exe msys64/ucrt64/bin/ld.exe \
         msys64/ucrt64/bin/gcc.exe \
         msys64/ucrt64/bin/qemu-system-x86_64.exe msys64/usr/bin/xorriso.exe \
         msys64/ucrt64/bin/mcopy.exe grub/grub-2.06-for-windows/grub-mkimage.exe; do
    [[ -x "$WIN_TOOLS/$f" ]] || { _win_tools_fail "missing $WIN_TOOLS/$f"; return 1; }
done

SHIM_DIR="$WIN_TOOLS/bin"
ELF_BIN="$WIN_TOOLS/elf/bin"
MINGW_BIN="$WIN_TOOLS/msys64/ucrt64/bin"

# Written on every source: a stale shim after an upgrade is worse than a few
# file writes, and the content is generated from the paths above.
mkdir -p "$SHIM_DIR"

cat > "$SHIM_DIR/as" <<SHIM
#!/usr/bin/env bash
# Generated by tools/win_toolchain.sh: PE sources need MinGW as, the rest ELF.
for arg in "\$@"; do
    case "\$(basename -- "\$arg")" in
        prog_pe*.s|prog_win32_*.s)
            exec "$MINGW_BIN/as.exe" "\$@" ;;
    esac
done
exec "$ELF_BIN/x86_64-elf-as.exe" "\$@"
SHIM

# MinGW's ld 2.47 does NOT honour SOURCE_DATE_EPOCH: two links a second apart
# carry different TimeDateStamps, and the bound-import composition reads that
# stamp back as a provider's identity, so it refuses the mismatch (measured).
# Linux's binutils performs the substitution itself; here both timestamp
# copies in the image are written over after the link, keeping every PE in one
# build carrying one stamp.
cat > "$SHIM_DIR/pe_stamp" <<'STAMP'
#!/usr/bin/env python3
"""Write SOURCE_DATE_EPOCH over a PE image's TimeDateStamp.

The header field is not the only copy: the linker also stamps the export
directory (data directory entry 0) with it, and the bound-import composition
reads THAT one back as the provider's identity. Both are written, translating
the directory's RVA to a file offset through the section table.
"""
import os
import struct
import sys

STAMP_VALUE = int(os.environ.get("SOURCE_DATE_EPOCH", "946684800"))
PE_MAGIC = b"PE" + bytes(2)


def rva_to_offset(sections, rva):
    for va, vsize, raw_ptr, raw_size in sections:
        if va <= rva < va + max(vsize, raw_size):
            return raw_ptr + (rva - va)
    return None


def stamp_file(path):
    with open(path, "r+b") as f:
        data = bytearray(f.read())
        if data[:2] != b"MZ":
            return
        off = struct.unpack_from("<I", data, 0x3C)[0]
        if bytes(data[off:off + 4]) != PE_MAGIC:
            return
        struct.pack_into("<I", data, off + 8, STAMP_VALUE)
        nsec = struct.unpack_from("<H", data, off + 6)[0]
        opt_size = struct.unpack_from("<H", data, off + 20)[0]
        opt = off + 24
        magic = struct.unpack_from("<H", data, opt)[0]
        dd = opt + (112 if magic == 0x20B else 96)
        nrva = struct.unpack_from("<I", data, dd - 4)[0]
        sections = []
        sec = opt + opt_size
        for i in range(nsec):
            base = sec + i * 40
            vsize, va = struct.unpack_from("<II", data, base + 8)
            raw_size, raw_ptr = struct.unpack_from("<II", data, base + 16)
            sections.append((va, vsize, raw_ptr, raw_size))
        if nrva > 0:
            export_rva = struct.unpack_from("<I", data, dd)[0]
            if export_rva:
                at = rva_to_offset(sections, export_rva)
                if at is not None and at + 4 <= len(data):
                    struct.pack_into("<I", data, at + 4, STAMP_VALUE)
        f.seek(0)
        f.write(data)


rc = 0
for arg in sys.argv[1:]:
    try:
        stamp_file(arg)
    except OSError as exc:
        print(f"pe_stamp: {arg}: {exc}", file=sys.stderr)
        rc = 1
sys.exit(rc)
STAMP

cat > "$SHIM_DIR/ld" <<SHIM
#!/usr/bin/env bash
# Generated by tools/win_toolchain.sh: -m i386pep is a PE link, else ELF.
pe=0
out=""
prev=""
for arg in "\$@"; do
    case "\$arg" in
        i386pep|-mi386pep) pe=1 ;;
    esac
    case "\$prev" in
        -o|--output) out="\$arg" ;;
    esac
    prev="\$arg"
done
if [[ "\$pe" == "1" ]]; then
    "$MINGW_BIN/ld.exe" "\$@" || exit \$?
    [[ -n "\$out" ]] && "$SHIM_DIR/pe_stamp" "\$out"
    exit 0
fi
exec "$ELF_BIN/x86_64-elf-ld.exe" "\$@"
SHIM

cat > "$SHIM_DIR/objdump" <<SHIM
#!/usr/bin/env bash
# Generated by tools/win_toolchain.sh: PE images go to MinGW objdump.
for arg in "\$@"; do
    case "\$arg" in
        *.dll|*.DLL|*.exe|*.EXE)
            exec "$MINGW_BIN/objdump.exe" "\$@" ;;
    esac
done
exec "$ELF_BIN/x86_64-elf-objdump.exe" "\$@"
SHIM

printf '#!/usr/bin/env bash\nexec "%s" "$@"\n' "$ELF_BIN/x86_64-elf-strip.exe" \
    > "$SHIM_DIR/strip"
printf '#!/usr/bin/env bash\nexec "%s" "$@"\n' "$ELF_BIN/x86_64-elf-readelf.exe" \
    > "$SHIM_DIR/readelf"
chmod +x "$SHIM_DIR"/as "$SHIM_DIR"/ld "$SHIM_DIR"/objdump \
         "$SHIM_DIR"/strip "$SHIM_DIR"/readelf "$SHIM_DIR"/pe_stamp

# QEMU's Windows build ships qemu-system-x86_64.exe, which bash finds from the
# bare name; the gates call it that way and need no .exe spelling.
#
# msys64/usr/bin goes LAST on purpose. It is an MSYS (POSIX-emulation) tree, and
# its coreutils include `link.exe`, `find.exe`, `sort.exe` and `timeout.exe` --
# names that also matter to Windows-native programs. Putting it first made
# rustc's MSVC host port invoke coreutils' `link.exe` ("link: extra operand")
# instead of a real linker, which is a silent, confusing break.
export PATH="$SHIM_DIR:$ELF_BIN:$MINGW_BIN:$WIN_TOOLS/grub/grub-2.06-for-windows:$PATH:$WIN_TOOLS/msys64/usr/bin"
export NYKERNEL_WIN_TOOLS="$WIN_TOOLS"

# Cargo builds every build script and proc macro for the HOST, and the pinned
# 1.99.1 toolchain here is the x86_64-pc-windows-msvc one, whose host links go
# through `link.exe` from an MSVC installation plus the Windows SDK import
# libraries. This machine has neither (no Visual Studio, no Windows Kits, no
# lld-link), so no host artifact -- and therefore no `cargo build-std` -- can be
# produced with the MSVC host port at all. The SAME rustc version is installed
# as an x86_64-pc-windows-gnu port, whose host links go through the MinGW gcc
# above (a real GCC driver, not a bare ld), so host build scripts link and run
# while the freestanding x86_64-nyrqis-kernel target is unaffected: that target
# names rust-lld itself and never involves the host linker.
#
# RUSTUP_TOOLCHAIN is the documented escape hatch that wins over
# rust-toolchain.toml, so the pin file still records the SUPPORTED pairing and
# this only redirects the host port. It is set with := so an explicit caller
# choice is never overridden.
if [[ -x "$MINGW_BIN/gcc.exe" ]]; then
    export RUSTUP_TOOLCHAIN="${RUSTUP_TOOLCHAIN:-1.99.1-x86_64-pc-windows-gnu}"
fi
